#!/usr/bin/env bash
#
# One-time setup of a fresh Ubuntu 24.04 droplet for Bhavishya PSCs.
# Run as root from your own computer:
#
#   ssh root@YOUR_IP 'ADMIN_EMAIL=you@example.com bash -s' < deploy/setup-server.sh
#
# Options (environment variables, all optional):
#   SITE=1.2.3.4            address the site is served at (default: this droplet's public IP).
#                           Use enable-https.sh later to move to a domain + HTTPS.
#   ADMIN_EMAIL=you@x.com   create this admin account; its password is printed once at the end.
#   BRANCH=main             git branch to deploy (and that later deploys follow).
#   DEMO=content            content: load the sample syllabus/notes/PYQs (no demo accounts)
#                           none:    start empty
#                           full:    sample content AND the demo accounts — public passwords,
#                                    only for a throwaway demo server.
#   GITHUB_DEPLOY_PUBKEY='ssh-ed25519 AAAA… github-deploy'
#                           authorise GitHub Actions to run deploy.sh (and nothing else).
#
# Safe to re-run: every step checks before it acts, .env files and the
# database password are kept, and services/nginx config are refreshed.
set -euo pipefail

[ "$(id -u)" = 0 ] || { echo "Run as root."; exit 1; }

REPO="${REPO:-https://github.com/BhavishyaIAS/Bhavishya.PSC.git}"
BRANCH="${BRANCH:-main}"
DEMO="${DEMO:-content}"
ADMIN_EMAIL="${ADMIN_EMAIL:-}"
APP=/home/deploy/bhavishya-psc
DB=bhavishya
SITE="${SITE:-$(curl -fsS --max-time 5 http://169.254.169.254/metadata/v1/interfaces/public/0/ipv4/address 2>/dev/null || hostname -I | awk '{print $1}')}"
run() { sudo -u deploy -H "$@"; }

echo "==> Setting up Bhavishya PSCs at http://$SITE (branch $BRANCH)"

# --- 1. deploy user, swap, firewall ----------------------------------------
if ! id deploy >/dev/null 2>&1; then
  echo "==> Creating the deploy user"
  adduser --disabled-password --gecos "" deploy
fi
chmod 755 /home/deploy

# `next build` needs more than 2 GB at peak; swap keeps a small droplet from OOM-ing.
if [ ! -f /swapfile ]; then
  echo "==> Adding a 2 GB swap file"
  fallocate -l 2G /swapfile && chmod 600 /swapfile && mkswap /swapfile >/dev/null && swapon /swapfile
  echo '/swapfile none swap sw 0 0' >> /etc/fstab
fi

# --- 2. software ---------------------------------------------------------------
echo "==> Installing packages (Python 3.12, PostgreSQL 16, nginx, Node 22)"
export DEBIAN_FRONTEND=noninteractive
apt-get update -q
apt-get install -y -q python3-venv python3-pip postgresql postgresql-contrib nginx git curl ufw \
  certbot python3-certbot-nginx
if ! command -v node >/dev/null || [ "$(node -v | cut -d. -f1)" != "v22" ]; then
  curl -fsSL https://deb.nodesource.com/setup_22.x | bash -
  apt-get install -y -q nodejs
fi
ufw allow OpenSSH >/dev/null
ufw allow 'Nginx Full' >/dev/null
ufw --force enable >/dev/null

# --- 3. database -------------------------------------------------------------------
ENV_FILE="$APP/backend/.env"
if [ -f "$ENV_FILE" ] && grep -q '^DATABASE_URL=' "$ENV_FILE"; then
  DB_PASSWORD=$(sed -n 's#^DATABASE_URL=postgres://[^:]*:\([^@]*\)@.*#\1#p' "$ENV_FILE")
else
  DB_PASSWORD=$(python3 -c "import secrets; print(secrets.token_urlsafe(24))")
fi
if ! sudo -u postgres psql -tAc "SELECT 1 FROM pg_roles WHERE rolname='$DB'" | grep -q 1; then
  echo "==> Creating the database"
  sudo -u postgres psql -qc "CREATE ROLE $DB LOGIN PASSWORD '$DB_PASSWORD';"
fi
if ! sudo -u postgres psql -tAc "SELECT 1 FROM pg_database WHERE datname='$DB'" | grep -q 1; then
  sudo -u postgres psql -qc "CREATE DATABASE $DB OWNER $DB;"
fi

# --- 4. code ---------------------------------------------------------------------------
if [ ! -d "$APP/.git" ]; then
  echo "==> Cloning $REPO ($BRANCH)"
  run git clone --branch "$BRANCH" "$REPO" "$APP"
fi
chown -R deploy:deploy "$APP"
echo "$BRANCH" > /home/deploy/.bhavishya-branch
cd "$APP"

echo "==> Backend: Python environment, settings, schema"
[ -d backend/.venv ] || run python3 -m venv backend/.venv
run backend/.venv/bin/pip install --quiet --upgrade pip
run backend/.venv/bin/pip install --quiet -r backend/requirements.txt

if [ ! -f "$ENV_FILE" ]; then
  SECRET=$(python3 -c "import secrets; print(secrets.token_urlsafe(50))")
  run tee "$ENV_FILE" >/dev/null <<EOF
# Generated by deploy/setup-server.sh — production. Never commit this file.
DEBUG=false
SECRET_KEY=${SECRET}
DATABASE_URL=postgres://${DB}:${DB_PASSWORD}@127.0.0.1:5432/${DB}
# 127.0.0.1: the Next.js server calls the API locally.
ALLOWED_HOSTS=${SITE},127.0.0.1,localhost
CSRF_TRUSTED_ORIGINS=http://${SITE}
# Plain HTTP on a bare IP: Secure cookies would never be sent back, so they must
# stay off until HTTPS is on (enable-https.sh flips this to true).
COOKIE_SECURE=false
SITE_URL=http://${SITE}
EOF
  chmod 600 "$ENV_FILE"
fi

M="run backend/.venv/bin/python backend/manage.py"
$M migrate --noinput
$M collectstatic --noinput --verbosity 0
run mkdir -p backend/media

FIRST_RUN=false
[ "$($M shell -c 'from content.models import Track; print(Track.objects.exists())' 2>/dev/null | tail -1)" = "True" ] || FIRST_RUN=true
if [ "$FIRST_RUN" = true ]; then
  case "$DEMO" in
    content) echo "==> Loading the sample content (no demo accounts)"; $M seed_demo --content-only ;;
    full)    echo "==> Loading the sample content AND demo accounts"; $M seed_demo ;;
    none)    echo "==> Starting empty (no sample content)"; $M shell -c "
from content.models import Commission, ExamGroup, Track
for o, (s, n) in enumerate([('group-1', 'Group 1'), ('group-2', 'Group 2')], 1):
    ExamGroup.objects.update_or_create(slug=s, defaults={'name': n, 'order': o})
for o, (s, short, name) in enumerate([('appsc', 'APPSC', 'Andhra Pradesh Public Service Commission'),
                                      ('tgpsc', 'TGPSC', 'Telangana Public Service Commission')], 1):
    c, _ = Commission.objects.update_or_create(slug=s, defaults={'short_name': short, 'name': name, 'order': o})
    for g in ExamGroup.objects.all():
        Track.objects.get_or_create(commission=c, group=g)
" ;;
  esac
fi

ADMIN_OUT=""
if [ -n "$ADMIN_EMAIL" ]; then
  ADMIN_OUT=$($M ensure_admin "$ADMIN_EMAIL")
fi

echo "==> Frontend: install and build (a few minutes)"
if [ ! -f frontend/.env.production.local ]; then
  run tee frontend/.env.production.local >/dev/null <<EOF
API_ORIGIN=http://127.0.0.1:8000
NEXT_PUBLIC_SHOW_DEMO_LOGINS=$([ "$DEMO" = full ] && echo true || echo false)
EOF
fi
run npm --prefix frontend ci --no-audit --no-fund --loglevel=error
run npm --prefix frontend run build

# --- 5. services + nginx -------------------------------------------------------------
echo "==> Installing services and the nginx site"
for unit in bhavishya-api bhavishya-web; do
  sed "s#APP#$APP#g" "deploy/$unit.service" > "/etc/systemd/system/$unit.service"
done
systemctl daemon-reload
systemctl enable --quiet bhavishya-api bhavishya-web
systemctl restart bhavishya-api bhavishya-web

# Keep the server_name certbot may already have set; otherwise use SITE.
NAMES=$(sed -n 's/^\s*server_name \(.*\);/\1/p' /etc/nginx/sites-available/bhavishya 2>/dev/null | head -1)
NAMES="${NAMES:-$SITE}"
if ! grep -q 'managed by Certbot' /etc/nginx/sites-available/bhavishya 2>/dev/null; then
  sed -e "s#SERVER_NAMES#$NAMES#" -e "s#APP#$APP#g" deploy/nginx.conf > /etc/nginx/sites-available/bhavishya
fi
ln -sf /etc/nginx/sites-available/bhavishya /etc/nginx/sites-enabled/bhavishya
rm -f /etc/nginx/sites-enabled/default
nginx -t -q
systemctl reload nginx

# --- 6. backups + GitHub deploy key ---------------------------------------------------
install -m 755 deploy/backup.sh /usr/local/bin/bhavishya-backup.sh
mkdir -p /home/deploy/backups && chown deploy:deploy /home/deploy/backups
# Built in a temp file: on a fresh box `crontab -l` exits 1, which under
# `set -eo pipefail` would silently end this script.
CRON_TMP=$(mktemp)
{ crontab -l 2>/dev/null || true; } | { grep -v 'bhavishya-backup' || true; } > "$CRON_TMP"
echo "30 20 * * * /usr/local/bin/bhavishya-backup.sh >> /home/deploy/backups/backup.log 2>&1  # 02:00 IST" >> "$CRON_TMP"
crontab "$CRON_TMP" && rm -f "$CRON_TMP"

if [ -n "${GITHUB_DEPLOY_PUBKEY:-}" ]; then
  mkdir -p /root/.ssh && touch /root/.ssh/authorized_keys && chmod 600 /root/.ssh/authorized_keys
  KEY_BODY=$(echo "$GITHUB_DEPLOY_PUBKEY" | awk '{print $2}')
  if ! grep -q "$KEY_BODY" /root/.ssh/authorized_keys; then
    echo "command=\"bash $APP/deploy/deploy.sh\",restrict $GITHUB_DEPLOY_PUBKEY" >> /root/.ssh/authorized_keys
    echo "==> GitHub Actions key authorised (it can only run deploy.sh)"
  fi
fi
git -C "$APP" rev-parse HEAD > /home/deploy/.deployed-commit

# --- 7. check ---------------------------------------------------------------------------------
sleep 4
echo
echo "==> Services: api $(systemctl is-active bhavishya-api), web $(systemctl is-active bhavishya-web)"
echo "==> Checks:   site $(curl -s -o /dev/null -w '%{http_code}' http://127.0.0.1/)  api $(curl -s -o /dev/null -w '%{http_code}' "http://127.0.0.1/api/commissions/" -H "Host: $SITE")"
echo
echo "============================================================"
echo " Bhavishya PSCs is live at  http://${SITE}"
[ -n "$ADMIN_OUT" ] && echo && echo "$ADMIN_OUT" | sed 's/^/ /'
cat <<EOF

 GitHub Actions secrets (repo → Settings → Secrets → Actions):
   DEPLOY_HOST         ${SITE}
   DEPLOY_KNOWN_HOSTS  ${SITE} $(awk '{print $1" "$2}' /etc/ssh/ssh_host_ed25519_key.pub)
   DEPLOY_SSH_KEY      the private half of GITHUB_DEPLOY_PUBKEY

 Deploy by hand:      ssh root@${SITE} bash ${APP}/deploy/deploy.sh
 Add a domain+HTTPS:  ssh root@${SITE} 'bash ${APP}/deploy/enable-https.sh example.com you@example.com'
 Logs:                journalctl -u bhavishya-api -u bhavishya-web -n 100
============================================================
EOF
